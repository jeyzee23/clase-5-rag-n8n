import fs from 'node:fs';
const md = fs.readFileSync(process.argv[2], 'utf8');
const code = fs.readFileSync(new URL('../js/02-chunking-por-titulos.js', import.meta.url), 'utf8');
const $input = { first: () => ({ json: { markdown: md, source: 'Reglamento-General-LPF-2025.pdf' } }) };
const out = new Function('$input', code)($input);
console.log('chunks:', out.length);
const sizes = out.map(o => o.json.chars);
console.log('min/max/avg chars:', Math.min(...sizes), Math.max(...sizes), Math.round(sizes.reduce((a,b)=>a+b)/sizes.length));
for (const o of out.slice(0, 4)) console.log('---', o.json.chunk, o.json.seccion, '\n', o.json.text.slice(0, 300));
const bad = out.filter(o => /Reglamento General de la Liga Profesional de Fútbol de AFA \d+/.test(o.json.text));
console.log('chunks con pie de página residual:', bad.length);
console.log('secciones únicas:', new Set(out.map(o=>o.json.seccion)).size);
const art8 = out.filter(o => o.json.seccion.includes('Artículo 8 '));
console.log('Artículo 8 → chunks:', art8.length);
